Test("Eval.Result.Diff compares with the previous best", function()
    local R = LoadModule("Eval.Result.lua")
    local Text, Kind = R.Diff(986246, nil, false, true)
    CheckEq(Text, "+986,246", "first play text")
    CheckEq(Kind, "first", "first play kind")
    Text, Kind = R.Diff(958873, 890450, false, true)
    CheckEq(Text, "+68,423", "up text")
    CheckEq(Kind, "up", "up kind")
    Text, Kind = R.Diff(900000, 900000, false, true)
    CheckEq(Text, "+0", "tie text")
    CheckEq(Kind, "up", "tie kind")
    Text, Kind = R.Diff(800000, 812345, false, true)
    CheckEq(Text, "-12,345", "down text")
    CheckEq(Kind, "down", "down kind")
    CheckEq(R.Diff(958873, 890450, true, true), nil, "broken play has no diff")
    CheckEq(R.Diff(958873, 890450, false, false), nil, "guest without profile has no diff")
end)

Test("Eval.Result.PreviousBest skips the current play and broken plays", function()
    local R = LoadModule("Eval.Result.lua")
    local function HS(Points, Grade)
        return { GetScore = function() return Points end, GetGrade = function() return Grade end }
    end
    local A, B = HS(950000, "Grade_Tier03"), HS(900000, "Grade_Tier05")
    local F = HS(990000, "Grade_Failed")
    CheckEq(R.PreviousBest({ A, B }, 0), B, "skips the play at index 0")
    CheckEq(R.PreviousBest({ A, B }, -1), A, "-1 skips nothing")
    CheckEq(R.PreviousBest({ A, B }, 1), A, "skips the second play")
    CheckEq(R.PreviousBest({ F, A }, -1), A, "broken play is not a record")
    CheckEq(R.PreviousBest({ A }, 0), nil, "only the current play")
    CheckEq(R.PreviousBest({}, -1), nil, "empty list")
    CheckEq(R.PreviousBest(nil, -1), nil, "no list")
end)

Test("Eval.Result.Counts folds judgements into the five rows", function()
    local R = LoadModule("Eval.Result.lua")
    local Values = { W1 = 10, W2 = 20, CheckpointHit = 5, W3 = 3, W4 = 2, W5 = 1, Miss = 4, CheckpointMiss = 6 }
    local C = R.Counts(function(Name) return Values[Name] end, 265, 42.1)
    CheckEq(C.perfect, 35, "perfect")
    CheckEq(C.great, 3, "great")
    CheckEq(C.good, 2, "good")
    CheckEq(C.bad, 1, "bad")
    CheckEq(C.miss, 10, "miss")
    CheckEq(C.maxCombo, 265, "maxCombo")
    CheckEq(C.kcal, 42.1, "kcal")
    local P = R.Counts(function(Name) return Values[Name] end, 265, 42.1, true)
    CheckEq(P.perfect, 15, "pump perfect = W1 + CheckpointHit")
    CheckEq(P.great, 20, "pump great = W2")
    CheckEq(P.good, 3, "pump good = W3")
    CheckEq(P.bad, 2, "pump bad = W4")
    CheckEq(P.miss, 10, "pump miss")
    CheckEq(P.maxCombo, 265, "pump maxCombo")
    CheckEq(P.kcal, 42.1, "pump kcal")
    CheckEq(R.Counts(function(Name) return Values[Name] end, 265, 42.1, false).perfect, 35, "pumpTiming false is the default")
    local Z = R.Counts(function() return nil end, 0, 0)
    CheckEq(Z.perfect, 0, "missing judgements count as zero")
    CheckEq(Z.miss, 0, "missing misses count as zero")
end)

