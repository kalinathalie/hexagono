Test("Eval.Result.IsImage accepts png, jpg, jpeg and bmp only", function()
    local R = LoadModule("Eval.Result.lua")
    Check(R.IsImage("bg.png"), "png")
    Check(R.IsImage("BG.JPG"), "upper case jpg")
    Check(R.IsImage("a.jpeg"), "jpeg")
    Check(R.IsImage("b.bmp"), "bmp")
    Check(R.IsImage("/Songs/x/y.PNG"), "path with upper case extension")
    CheckEq(R.IsImage("bg.mp4"), false, "video")
    CheckEq(R.IsImage("x.gif"), false, "gif")
    CheckEq(R.IsImage(nil), false, "nil")
    CheckEq(R.IsImage(""), false, "empty")
    CheckEq(R.IsImage("png"), false, "no dot")
end)

