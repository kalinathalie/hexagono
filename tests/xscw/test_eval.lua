-- Eval.Result: logic of the result screen (Phoenix 2 style). Pure Lua.

Test("Eval.Result.Count pads to at least three digits", function()
    local R = LoadModule("Eval.Result.lua")
    CheckEq(R.Count(26), "026", "two digits")
    CheckEq(R.Count(0), "000", "zero")
    CheckEq(R.Count(1760), "1760", "four digits")
    CheckEq(R.Count(nil), "000", "nil")
end)

Test("Eval.Result.Kcal prints three decimals in seven characters", function()
    local R = LoadModule("Eval.Result.lua")
    CheckEq(R.Kcal(42.1236), "042.124", "rounded and padded")
    CheckEq(R.Kcal(0), "000.000", "zero")
    CheckEq(R.Kcal(nil), "000.000", "nil")
    CheckEq(R.Kcal(123.4), "123.400", "three integer digits")
    CheckEq(R.Kcal(-1), "000.000", "negative")
end)

Test("Eval.Result.ScoreText pads to seven digits with z", function()
    local R = LoadModule("Eval.Result.lua")
    CheckEq(R.ScoreText(958873), "z958873", "leading zero becomes z")
    CheckEq(R.ScoreText(0), "zzzzzz0", "zero keeps the last digit")
    CheckEq(R.ScoreText(1000000), "1000000", "seven digits keep inner zeros")
    CheckEq(R.ScoreText(986246.9), "z986246", "floored")
    CheckEq(R.ScoreText(12345678), "12345678", "more than seven digits")
    CheckEq(R.ScoreText(nil), "zzzzzz0", "nil is zero")
    CheckEq(R.ScoreText(-5), "zzzzzz0", "negative is zero")
end)

