    }
    for I, W in ipairs(Want) do
        CheckEq(R.ROWS[I].key, W[1], "row " .. I .. " key")
        CheckEq(R.ROWS[I].text, W[2], "row " .. I .. " text")
        CheckEq(R.ROWS[I].art, W[3], "row " .. I .. " art")
    end
end)

Test("Eval.Result.IsCounting is true while the table or the score counts (the tick plays then)", function()
    local R = LoadModule("Eval.Result.lua")
    CheckEq(R.IsCounting(0.99), false, "before the table counts")
    CheckEq(R.IsCounting(1.0), true, "table starts")
    CheckEq(R.IsCounting(1.79), true, "table still counting")
    CheckEq(R.IsCounting(1.8), false, "table done, score not started")
    CheckEq(R.IsCounting(1.99), false, "gap before the score")
    CheckEq(R.IsCounting(2.0), true, "score starts")
    CheckEq(R.IsCounting(2.49), true, "score still counting")
    CheckEq(R.IsCounting(2.5), false, "score done")
end)
