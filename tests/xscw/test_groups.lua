local Filter = LoadModule("Select.GroupFilter.lua")
local function G(names) local t = {} for i, n in ipairs(names) do t[i] = { Name = n, SubGroups = { { Name = n .. " 1" } } } end return t end

Test("GroupFilter: two players lose Double, Half-Double and the Co-op special group", function()
    local L = G({ "Special", "Group", "Single", "Half-Double", "Double" })
    L[1].SubGroups = { { Name = "All Tunes" }, { Name = "Co-op" }, { Name = "Remix" } }
    local Out = Filter.ForPlayers(L, 2)
    CheckEq(#Out, 3, "three categories left")
    CheckEq(Out[3].Name, "Single", "single stays")
    CheckEq(#Out[1].SubGroups, 2, "co-op removed from special"); CheckEq(Out[1].SubGroups[2].Name, "Remix", "remix stays")
end)

Test("GroupFilter: one player keeps everything", function()
    local L = G({ "Special", "Double" }); L[1].SubGroups = { { Name = "Co-op" } }
    local Out = Filter.ForPlayers(L, 1)
    CheckEq(#Out, 2, "both categories"); CheckEq(Out[1].SubGroups[1].Name, "Co-op", "co-op stays")
end)

Test("GroupFilter: a category left empty is removed", function()
    local L = G({ "Special", "Single" }); L[1].SubGroups = { { Name = "Co-op" } }
    local Out = Filter.ForPlayers(L, 2)
    CheckEq(#Out, 1, "special gone"); CheckEq(Out[1].Name, "Single", "single")
end)
