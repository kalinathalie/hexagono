-- Co-op charts: each player's notes in their own color. Gameplay.Coop (the theme side) and
-- the hexagono-coop noteskin's element resolution (pi/config/noteskins/hexagono-coop).

Test("Coop.IsCoop: charts the engine counts more than one player for, or described COOP", function()
    local C = LoadModule("Gameplay.Coop.lua")
    CheckEq(C.IsCoop(2, "DP COOP 2P"), true, "2 players")
    CheckEq(C.IsCoop(5, ""), true, "5 players, no description")
    CheckEq(C.IsCoop(0, "COOP x3"), true, "no count, COOP in the description")
    CheckEq(C.IsCoop(nil, "dp coop 2p"), true, "description in lower case")
    CheckEq(C.IsCoop(1, "DP"), false, "one player")
    CheckEq(C.IsCoop(nil, nil), false, "nothing known")
    CheckEq(C.IsCoop(0, "S10 COOPER"), true, "any COOP in the description counts (as the theme's co-op group)")
end)

Test("Coop.Choosable hides the co-op noteskin from the noteskin lists", function()
    local C = LoadModule("Gameplay.Coop.lua")
    local Names = C.Choosable({ "default", "hexagono-coop", "SanityP1", "Hexagono-Coop", "fiesta_2" })
    CheckEq(#Names, 3, "two co-op entries removed")
    CheckEq(Names[1], "default", "order kept")
    CheckEq(Names[2], "SanityP1", "the color skins stay")
    CheckEq(Names[3], "fiesta_2", "the rest stays")
    CheckEq(C.SKIN, "hexagono-coop", "the noteskin name")
end)

local function Skin() return dofile("pi/config/noteskins/hexagono-coop/NoteSkin.lua") end

Test("hexagono-coop: player 1 and plain elements use SanityP1's own art", function()
    local S = Skin()
    local B, E = S.Resolve("DownLeft", "Tap Note", false)
    CheckEq(B .. "|" .. E, "DownLeft|Tap Note", "tap note")
    B, E = S.Resolve("Center", "Hold Head Active", false)
    CheckEq(B .. "|" .. E, "Center|Tap Note", "hold head is the tap note")
    B, E = S.Resolve("UpRight", "Receptor", false)
    CheckEq(B .. "|" .. E, "UpLeft|Receptor", "receptor from UpLeft, as in SanityP")
    B, E = S.Resolve("DownRight", "Explosion", false)
    CheckEq(B .. "|" .. E, "UpLeft|Explosion", "explosion from UpLeft")
end)

Test("hexagono-coop: players 2-5 get their renamed note art", function()
    local S = Skin()
    local B, E = S.Resolve("DownLeft", "P2 Tap Note", false)
    CheckEq(B .. "|" .. E, "DownLeft|P2 Tap Note", "P2 tap")
    B, E = S.Resolve("Center", "P3 Hold Head Inactive", false)
    CheckEq(B .. "|" .. E, "Center|P3 Tap Note", "P3 hold head")
    B, E = S.Resolve("UpLeft", "P5 Hold Body Active", false)
    CheckEq(B .. "|" .. E, "UpLeft|P5 Hold Body Active", "P5 hold body")
    B, E = S.Resolve("UpLeft", "P4 Roll Bottomcap Inactive", false)
    CheckEq(B .. "|" .. E, "UpLeft|P4 Roll Bottomcap Inactive", "P4 roll cap")
    B, E = S.Resolve("UpLeft", "P7 Tap Note", false)
    CheckEq(B .. "|" .. E, "UpLeft|P2 Tap Note", "P7 wraps to the second color")
    B, E = S.Resolve("UpLeft", "P6 Tap Note", false)
    CheckEq(B .. "|" .. E, "UpLeft|Tap Note", "P6 wraps to the first color")
end)

Test("hexagono-coop: elements without per-player art never ask for a P file", function()
    local S = Skin()
    local B, E = S.Resolve("DownLeft", "P2 Receptor", false)
    CheckEq(B .. "|" .. E, "UpLeft|Receptor", "receptor is shared")
    B, E = S.Resolve("DownLeft", "P2 Hold Topcap Inactive", false)
    CheckEq(B .. "|" .. E, "DownLeft|Hold Topcap Active", "topcap: SanityP's redirect, no P art")
    B, E = S.Resolve("DownLeft", "P3 Tap Mine", false)
    CheckEq(B .. "|" .. E, "UpLeft|Tap Mine", "mine is shared")
end)

Test("hexagono-coop: blanks, items and lifts as in SanityP", function()
    local S = Skin()
    local B, E, Kind = S.Resolve("DownLeft", "Hold Tail Active", false)
    CheckEq(E, nil, "hold tail is blank")
    B, E, Kind = S.Resolve("DownLeft", "P2 Roll Tail Inactive", false)
    CheckEq(E, nil, "P2 roll tail is blank")
    B, E, Kind = S.Resolve("Center", "Tap Note", true)
    CheckEq(B, "UpLeft", "items load from UpLeft")
    B, E, Kind = S.Resolve("Center", "P2 Tap Lift", false)
    CheckEq(E .. "|" .. tostring(Kind), "P2 Tap Note|lift", "lift is the tap note, pulsing")
end)
