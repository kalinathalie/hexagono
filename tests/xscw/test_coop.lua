-- Co-op charts: each player's notes in their own color, on the player's own noteskin.
-- Gameplay.Coop (the theme side) and the co-op script of "<noteskin>-coop"
-- (pi/config/noteskins/coop/NoteSkin.lua).

Test("Coop.IsCoop: charts the engine counts more than one player for, or described COOP", function()
    local C = LoadModule("Gameplay.Coop.lua")
    CheckEq(C.IsCoop(2, "DP COOP 2P"), true, "2 players")
    CheckEq(C.IsCoop(5, ""), true, "5 players, no description")
    CheckEq(C.IsCoop(0, "COOP x3"), true, "no count, COOP in the description")
    CheckEq(C.IsCoop(nil, "dp coop 2p"), true, "description in lower case")
    CheckEq(C.IsCoop(1, "DP"), false, "one player")
    CheckEq(C.IsCoop(nil, nil), false, "nothing known")
end)

Test("Coop.SkinFor names the co-op version of the player's noteskin", function()
    local C = LoadModule("Gameplay.Coop.lua")
    CheckEq(C.SkinFor("nx2"), "nx2-coop", "nx2")
    CheckEq(C.SkinFor("fiesta_2-prime"), "fiesta_2-prime-coop", "a name with a dash")
    CheckEq(C.SkinFor("nx2-coop"), "nx2-coop", "already the co-op one")
    CheckEq(C.SkinFor(nil), nil, "no noteskin")
end)

Test("Coop.Choosable hides the co-op noteskins and their color copies", function()
    local C = LoadModule("Gameplay.Coop.lua")
    local Names = C.Choosable({ "default", "nx2-coop", "nx2-coop3", "SanityP1", "hexagono-coop", "my-cooper", "fiesta_2" })
    CheckEq(#Names, 4, "three generated entries removed")
    CheckEq(Names[1], "default", "order kept")
    CheckEq(Names[2], "SanityP1", "a real noteskin stays")
    CheckEq(Names[3], "my-cooper", "a name that only looks alike stays")
    CheckEq(Names[4], "fiesta_2", "the rest stays")
end)

local function Skin(BaseName)
    Base = BaseName
    local S = dofile("pi/config/noteskins/coop/NoteSkin.lua")
    Base = nil
    return S
end

Test("co-op script: player 1's notes from the red copy, shared parts from the noteskin itself", function()
    local S = Skin("nx2")
    local K, E = S.Resolve("Tap Note")
    CheckEq(K .. "|" .. E, "nx2-coop1|Tap Note", "P1 tap")
    K, E = S.Resolve("Hold Body Active")
    CheckEq(K .. "|" .. E, "nx2-coop1|Hold Body Active", "P1 hold body")
    K, E = S.Resolve("Receptor")
    CheckEq(K .. "|" .. E, "nx2|Receptor", "receptor: the noteskin's own, every column")
    K, E = S.Resolve("Explosion")
    CheckEq(K .. "|" .. E, "nx2|Explosion", "explosion: the noteskin's own")
    K, E = S.Resolve("Tap Mine")
    CheckEq(K .. "|" .. E, "nx2|Tap Mine", "mines are nobody's")
end)

Test("co-op script: players 2-5 from their copies, the colors repeat from the 6th", function()
    local S = Skin("fiesta_2")
    local K, E = S.Resolve("P2 Tap Note")
    CheckEq(K .. "|" .. E, "fiesta_2-coop2|Tap Note", "P2 tap")
    K, E = S.Resolve("P3 Hold Head Inactive")
    CheckEq(K .. "|" .. E, "fiesta_2-coop3|Hold Head Inactive", "P3 hold head, the copy's own redirect")
    K, E = S.Resolve("P5 Roll Bottomcap Active")
    CheckEq(K .. "|" .. E, "fiesta_2-coop5|Roll Bottomcap Active", "P5 roll cap")
    K, E = S.Resolve("P2 Tap Lift")
    CheckEq(K .. "|" .. E, "fiesta_2-coop2|Tap Lift", "P2 lift")
    K, E = S.Resolve("P6 Tap Note")
    CheckEq(K .. "|" .. E, "fiesta_2-coop1|Tap Note", "P6 takes the first color")
    K, E = S.Resolve("P7 Tap Fake")
    CheckEq(K .. "|" .. E, "fiesta_2-coop2|Tap Fake", "P7 takes the second color")
    K, E = S.Resolve("P2 Receptor")
    CheckEq(K .. "|" .. E, "fiesta_2|Receptor", "a player's receptor is the shared one")
end)
